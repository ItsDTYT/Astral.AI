test('profile namespaces isolate memories, deleted-fact suppression, and old conversations', t => {
    const { store } = fixture(t);
    const one = store.state.profiles[0];
    const two = store.action({ type: 'saveProfile', profile: { displayName: 'Other person', facts: [{ text: 'Blue journal' }] } });
    const chat = profile => store.action({ type: 'createConversation', mode: 'normal', characterId: 'hina', userProfileId: profile.id });
    const a = chat(one), b = chat(two);
    const memory = store.action({ type: 'saveMemory', mode: 'normal', conversationId: a.id, memory: { text: 'Green journal', scope: 'character' } });
    assert.match(buildMemoryPrompt(store.state, a.id), /Green journal/);
    assert.doesNotMatch(buildMemoryPrompt(store.state, b.id), /Green journal/);
    store.action({ type: 'deleteMemory', mode: 'normal', conversationId: a.id, memoryId: memory.id });
    assert.equal(store.state.tombstones[0].userProfileId, one.id);
    store.action({ type: 'applyAutoMemory', mode: 'normal', conversationId: b.id, expectedCursor: 0, cursor: 4, facts: [{ text: 'Green journal', scope: 'character' }, { text: 'Blue journal', scope: 'character' }] });
    assert.match(buildMemoryPrompt(store.state, b.id), /Green journal/);
    assert.doesNotMatch(buildMemoryPrompt(store.state, b.id), /Blue journal/);
    store.action({ type: 'deleteProfile', profileId: two.id });
    const historical = store.state.conversations.find(c => c.id === b.id);
    assert.equal(historical.userProfileId, two.id); assert.equal(historical.shareProfile, false);
    assert(!store.state.memories.some(m => m.userProfileId === two.id));
    assert.throws(() => chat(two), /profile/i);
    validateState(structuredClone(store.state));
});
