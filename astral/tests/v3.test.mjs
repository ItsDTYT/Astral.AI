test('runner credentials stay on the exact managed origin and are never followed through redirects', async t => {
    const seen = [];
    const server = http.createServer((req, res) => { seen.push(req.headers.authorization); if (req.url === '/redirect') { res.writeHead(302, { location: '/other' }); res.end(); } else res.end('ok'); });
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const base = `http://127.0.0.1:${server.address().port}`;
    t.after(() => { forgetRunner(base); server.close(); });
    await runnerFetch(base); registerRunner(base, 'private-fixture-key'); await runnerFetch(base);
    assert.deepEqual(seen, [undefined, 'Bearer private-fixture-key']);
    await assert.rejects(runnerFetch(base + '/redirect'), /redirect/i);
    assert.equal(seen.length, 3); forgetRunner(base); await runnerFetch(base); assert.equal(seen.at(-1), undefined);
});
