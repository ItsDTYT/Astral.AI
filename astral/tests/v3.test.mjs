test('restore rolls back replaced files if a later copy fails', async t => {
    const { root, store } = fixture(t);
    fs.mkdirSync(path.join(root, 'characters')); fs.writeFileSync(path.join(root, 'characters/a.png'), 'old a'); fs.writeFileSync(path.join(root, 'characters/b.png'), 'old b');
    const archive = path.join(root, 'backup.zip'), zip = archiver('zip'), output = fs.createWriteStream(archive);
    const done = new Promise(resolve => output.on('close', resolve)); zip.pipe(output);
    zip.append(JSON.stringify({ format: 'astral-backup', version: 2, state: store.state }), { name: 'state.json' });
    zip.append('new a', { name: 'characters/a.png' }); zip.append('new b', { name: 'characters/b.png' });
    await zip.finalize(); await done;
    let copies = 0;
    await assert.rejects(restoreZip(archive, store, root, { copyFile: async (...args) => { if (++copies === 2) throw new Error('simulated disk failure'); await fs.promises.copyFile(...args); } }), /simulated disk failure/);
    assert.equal(fs.readFileSync(path.join(root, 'characters/a.png'), 'utf8'), 'old a');
    assert.equal(fs.readFileSync(path.join(root, 'characters/b.png'), 'utf8'), 'old b');
    for (const unsafe of ['characters/CON.png', 'chats/a:b.jsonl', 'characters/x./a.png', 'characters/../a.png', 'characters/\\a.png']) assert(!validBackupPath(unsafe));
});
