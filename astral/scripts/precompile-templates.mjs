import fs from 'node:fs';
import path from 'node:path';
import Handlebars from 'handlebars';
const templates = [];
function walk(folder) {
    for (const entry of fs.readdirSync(folder, { withFileTypes: true })) {
        const file = path.join(folder, entry.name);
        if (entry.isDirectory()) walk(file);
        else if (entry.name.endsWith('.html')) templates.push([`/${file.replaceAll('\\', '/')}`, Handlebars.precompile(fs.readFileSync(file, 'utf8'))]);
    }
}
walk('public/scripts/templates');
walk('public/scripts/extensions');
fs.writeFileSync('public/astral/templates.js', `// Generated by astral/scripts/precompile-templates.mjs.\nimport { Handlebars } from '../lib.js';\nexport const templates = new Map([\n${templates.map(([file, spec]) => `[${JSON.stringify(file.replace('/public/', '/'))}, Handlebars.template(${spec})]`).join(',\n')}\n]);\n`);
console.log(`Precompiled ${templates.length} bundled templates.`);
